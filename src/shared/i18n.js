let current = 'zh';

function setLang(lang) {
  current = dict[lang] ? lang : 'zh';
}
function getLang() {
  return current;
}
function t(key, ...args) {
  let s = (dict[current] && dict[current][key]) != null ? dict[current][key] : dict.zh[key];
  if (s == null) return key;
  args.forEach((a, i) => {
    s = String(s).split('{' + i + '}').join(a);
  });
  return s;
}

module.exports = { setLang, getLang, t };
